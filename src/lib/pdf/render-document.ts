import { PDFDocument, StandardFonts, rgb } from "pdf-lib";

type PdfDocumentInput = {
  title: string;
  summary: string | null;
  body: string;
  documentType: string;
};

function wrapText(text: string, maxLength: number) {
  const words = text.split(/\s+/);
  const lines: string[] = [];
  let current = "";

  words.forEach((word) => {
    if (`${current} ${word}`.trim().length > maxLength) {
      lines.push(current);
      current = word;
    } else {
      current = `${current} ${word}`.trim();
    }
  });

  if (current) lines.push(current);
  return lines;
}

export async function renderDocumentPdf(input: PdfDocumentInput) {
  const pdfDoc = await PDFDocument.create();
  let page = pdfDoc.addPage([612, 792]);
  const { height } = page.getSize();
  const font = await pdfDoc.embedFont(StandardFonts.Helvetica);
  const bold = await pdfDoc.embedFont(StandardFonts.HelveticaBold);
  let y = height - 64;

  page.drawText("PermitPilot", {
    x: 48,
    y,
    size: 20,
    font: bold,
    color: rgb(0.02, 0.18, 0.15),
  });
  page.drawText("AI construction admin", {
    x: 48,
    y: y - 18,
    size: 10,
    font,
    color: rgb(0.28, 0.36, 0.42),
  });

  y -= 64;
  page.drawText(input.title, {
    x: 48,
    y,
    size: 18,
    font: bold,
    color: rgb(0.02, 0.18, 0.15),
  });
  y -= 22;
  page.drawText(input.documentType.toUpperCase(), {
    x: 48,
    y,
    size: 9,
    font: bold,
    color: rgb(0.0, 0.45, 0.32),
  });
  y -= 28;

  if (input.summary) {
    wrapText(input.summary, 82).forEach((line) => {
      page.drawText(line, {
        x: 48,
        y,
        size: 11,
        font,
        color: rgb(0.18, 0.25, 0.32),
      });
      y -= 15;
    });
    y -= 14;
  }

  wrapText(input.body, 88).forEach((line) => {
    if (y < 64) {
      page = pdfDoc.addPage([612, 792]);
      y = height - 64;
    }

    page.drawText(line, {
      x: 48,
      y,
      size: 11,
      font,
      color: rgb(0.08, 0.12, 0.18),
    });
    y -= 16;
  });

  page.drawText("Generated by PermitPilot. Review before external submission.", {
    x: 48,
    y: 40,
    size: 9,
    font,
    color: rgb(0.44, 0.5, 0.56),
  });

  return pdfDoc.save();
}
